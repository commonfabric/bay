// NextSurfaceID returns the next surface ID (max+1) for the bay.
func (b *Bay) NextSurfaceID() int {
	max := 0
	for _, s := range b.Surfaces {
		if s.ID > max {
			max = s.ID
		}
	}
	return max + 1
}

